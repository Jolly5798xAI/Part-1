"""Write docs/EP13_SHOT_PLAN.md from the timeline (timeline_ep13.py) and the shot descriptions in scripts/render3d/shots.js."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import timeline_ep13 as TL

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
js = open(os.path.join(ROOT, "scripts", "render3d", "shots.js"), encoding="utf8").read()
DESC = {m.group(1): m.group(2).replace("\\'", "'") for m in re.finditer(r"^\s+(\w+): \{ desc: '((?:[^'\\]|\\.)*)'", js, re.M)}
src_job = {}
for m in re.finditer(r'(?:still|anim)\("(\w+)", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1)] = m.group(2)
for m in re.finditer(r'still\(f"(\w+)_\{m\}", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1) + "_neutral"] = m.group(2)
REUSED = {"E12_two": "EP12's last frame (ELENA_204 beside ALEX_48, the side monitor with the feed), reused unchanged from ../EP12/scenes — the feed is drawn by phone_ui (draw_live13)", "E12_two_neutral": "EP12's last frame, reused unchanged"}

def vo_for(a, b):
    return " ".join(re.sub(r"[*!]", "", t).replace("¡", "!") for s, e, t in TL.SUBS if s < b and e > a) or "—"   # EP10: ¡ is a literal «!»


rows = []
for i, s in enumerate(TL.SHOTS, 1):
    a, b = s["t"]; src = s["src"]
    if src == "BLACK": frame, desc = "black", "—"
    elif src == "LIPSYNC": frame = f"LIPSYNC `{s['lips']}_*`"; desc = REUSED.get(s["lips"]) or DESC.get(src_job.get(s["lips"] + "_neutral", ""), "")
    else: frame = f"`{src}`"; desc = REUSED.get(src) or DESC.get(src_job.get(src, src), "") or DESC.get(src, "")
    extra = [f"{k}: {s[k]}" for k in ("monitor", "monitors", "phone", "screens") if s.get(k)] + ([f"fx: {', '.join(s['fx'])}"] if s.get("fx") else []) + (["animated"] if "anim" in s else [])
    rows.append(f"| {i} | {a:.2f}–{b:.2f} | {frame} | {vo_for(a, b)} | {desc}{' · ' + '; '.join(extra) if extra else ''} |")
md = ["# EP13 «ПОСЛЕДНЯЯ КОПИЯ» — shot plan", "",
      f"Built from the final voiceover ({TL.VO_END:.2f} s, VO clock). Source of truth: `scripts/timeline_ep13.py`; this table is generated by",
      f"`scripts/08_shot_plan.py`. The episode stops dead on «…моё лицо» at {TL.END:.2f} s (the MP3's end, no black tail, no end card).",
      "No shot is longer than 4.5 s. Production names (ALEX_48 / ALEX_ORIGINAL_CONSCIOUSNESS / ELENA_1 / ELENA_0) never appear on screen.", "",
      "| # | time | frame | VO | picture / notes |", "|---|---|---|---|---|"] + rows + ["",
      "Not shown, on purpose (EP14–EP15): why the system calls copy 48 its creator, who started the first test, why the original disabled the",
      "brakes, which Elena tells the truth, whether the game can be stopped without Elena dying, what deleting the creator would do.",
      "The hidden recording never shows a collision: the original on the back seat flips «Отключить тормоза» and the recording ends there.", "",
      "## On-screen texts (exact, drawn in code with the series fonts, none before the VO says it)",
      f"Second phone (the recording): «{TL.MSG_BRAKES}» ({TL.T_CMDON:.2f}), switched on {TL.T_TOGGLE:.2f}.",
      f"Turned screen: «{TL.MSG_LAST}» ({TL.T_LAST:.2f}), «{TL.MSG_N48}» + «48» ({TL.T_N48:.2f}); «{TL.MSG_OPT1}» ({TL.T_OPT1:.2f}), «{TL.MSG_OPT2}» ({TL.T_OPT2:.2f}),",
      f"«{TL.MSG_PRICE}» under the second ({TL.T_PRICE:.2f}); countdown " + ", ".join(f"{v} ({t:.2f})" for t, v in TL.TICKS) + ";",
      f"«{TL.MSG_STOP1}» ({TL.T_MSG1:.2f}) «{TL.MSG_STOP2}» ({TL.T_MSG2:.2f}); from {TL.T_FACES:.2f} every screen shows ALEX_48's face.",
      f"Wrists: «1» on ELENA_1 (lit ~10.6), «0» on ELENA_0 on the feed ({TL.T_ZERO:.2f}), «48» on ALEX_48 vanishing {TL.T_VANISH:.2f}, «{TL.MSG_WORD}» from {TL.T_WORD0:.2f} (complete {TL.T_WORD:.2f}).", ""]
open(os.path.join(ROOT, "docs", "EP13_SHOT_PLAN.md"), "w", encoding="utf8").write("\n".join(md))
print("wrote docs/EP13_SHOT_PLAN.md", len(rows), "shots")
