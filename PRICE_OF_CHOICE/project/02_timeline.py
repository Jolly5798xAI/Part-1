#!/usr/bin/env python3
"""Build the machine-readable timeline + generation prompts from project/shots.py and timeline/EP01_words.json.

Outputs
  timeline/EP01_timeline.json   — every segment: scene, shot, start/end (output seconds AND frames @24fps),
                                  spoken phrase, visual, source file, camera, transition, sfx, on-screen text
  prompts/EP01_prompts.json     — per-shot generation package (prompt, negative, refs, camera, light, continuity)
  prompts/EP01_prompts.md       — the same, human-readable
"""
import json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "project"))
import shots as S

def out_t(t):
    """source-voiceover time -> output timeline time"""
    return round(t + sum(p for at, p in S.PAUSES if at <= t), 3)

words = json.load(open(ROOT / "timeline/EP01_words.json"))["words"]
end_src = S.CUT_TO_BLACK
segs = []
for i, sh in enumerate(S.SHOTS):
    a = sh["start"]
    b = S.SHOTS[i + 1]["start"] if i + 1 < len(S.SHOTS) else end_src
    oa, ob = out_t(a), out_t(b)
    # a pause that falls exactly on a cut belongs to the NEXT shot (the knocks / silence play on the new picture)
    if any(abs(at - a) < 1e-6 for at, _ in S.PAUSES):
        oa = round(a + sum(p for at, p in S.PAUSES if at < a), 3)
    if any(abs(at - b) < 1e-6 for at, _ in S.PAUSES):
        ob = round(b + sum(p for at, p in S.PAUSES if at < b), 3)
    phrase = " ".join(w["text"] for w in words if a <= w["start"] < b)
    fa, fb = round(oa * S.FPS), round(ob * S.FPS)
    if sh["kind"] == "ui":
        source = f"assets/ui/{sh['id']}.mp4"
        alt = []
    else:
        source = f"scenes/{sh['id']}.mp4"
        alt = [f"scenes/{sh['id']}.png", f"scenes/{sh['id']}.jpg"]
    segs.append(dict(
        scene=sh["scene"], shot=sh["id"], kind=sh["kind"],
        start=oa, end=ob, duration=round(ob - oa, 3), frame_in=fa, frame_out=fb, frames=fb - fa,
        source_vo_start=a, source_vo_end=b,
        phrase=phrase, anchor=sh.get("anchor"),
        visual=sh["visual_ru"], source=source, source_alternatives=alt,
        ui_template=sh.get("ui"), screen_insert=sh.get("screen"),
        camera=sh.get("camera"), transition=sh.get("transition"),
        on_screen_text=sh.get("on_screen"),
        sfx=[dict(t=out_t(t) if not any(abs(at - t) < 1e-6 for at, _ in S.PAUSES) else round(t + sum(p for at, p in S.PAUSES if at < t), 3),
                  effect=e, gain_db=g) for t, e, g in sh.get("sfx", [])],
        note=sh.get("note"),
    ))

cut = out_t(end_src)
tl = dict(
    title="ЦЕНА ВЫБОРА — Episode 01 «СТАКАН ВОДЫ»",
    fps=S.FPS, width=S.W, height=S.H,
    voiceover="audio/ElevenLabs_2026-11-06T01_50_20_Artem Lebedev - Captivating and Engaging_eleven_v3.mp3",
    voiceover_duration_source=74.919,
    atmospheric_pauses=[dict(source_t=at, output_t=out_t(at) - p, seconds=p) for at, p in S.PAUSES],
    hard_cut_to_black=cut, end_card=dict(start=cut, end=round(cut + S.END_CARD, 3), text=list(S.END_CARD_TEXT)),
    duration=round(cut + S.END_CARD, 3), total_frames=round((cut + S.END_CARD) * S.FPS),
    segments=segs,
)
(ROOT / "timeline").mkdir(exist_ok=True)
json.dump(tl, open(ROOT / "timeline/EP01_timeline.json", "w"), ensure_ascii=False, indent=1)

# ---- prompts
def fill(p):
    for k, v in S.CONT.items():
        p = p.replace("{" + k + "}", v)
    return p
pk, md = [], ["# EP01 — generation prompts (one package per live-action shot)\n",
              "Generated by `project/02_timeline.py` from `project/shots.py`. Do not edit by hand — edit shots.py and re-run.\n",
              f"**Global style suffix** (append to every prompt):\n\n> {S.STYLE}\n",
              f"**Global negative prompt:**\n\n> {S.NEGATIVE}\n",
              "**Rules:** always attach the listed reference images (image-to-image / character reference / first-frame). "
              "Generate at 1080×1920 or larger, 24 fps, 3–6 s clips (the editor trims to the exact frame count below). "
              "Phone screens stay plain — the exact Cyrillic UI is composited from `assets/ui/screens/`.\n"]
for s, sh in zip(segs, S.SHOTS):
    if sh["kind"] != "live":
        continue
    item = dict(shot=sh["id"], scene=sh["scene"], duration_s=s["duration"], frames=s["frames"],
                prompt=fill(sh["prompt"]) + ". " + S.STYLE, negative_prompt=S.NEGATIVE,
                references=[S.REF[r] for r in sh["refs"]], camera=sh["camera"], lighting=sh["light"],
                continuity=[S.CONT[r] for r in sh["refs"] if r in S.CONT] + (["Phone screen plain, UI composited later: " + sh["screen"]] if sh.get("screen") else []),
                fallback_note=sh.get("note"), output=s["source"])
    pk.append(item)
    md += [f"\n## {sh['id']} — scene {sh['scene']} · {s['duration']:.2f}s ({s['frames']} frames @24)\n",
           f"*VO:* «{s['phrase']}»\n", f"*Shot (RU):* {sh['visual_ru']}\n",
           f"**Prompt:**\n\n```\n{item['prompt']}\n```\n",
           f"**References:** {', '.join(item['references'])}  \n**Camera:** {item['camera']}  \n**Light:** {item['lighting']}  \n**Save as:** `{item['output']}` (or `.png` still)\n"]
    if sh.get("note"):
        md.append(f"> ⚠ {sh['note']}\n")
(ROOT / "prompts").mkdir(exist_ok=True)
json.dump(dict(style=S.STYLE, negative=S.NEGATIVE, shots=pk), open(ROOT / "prompts/EP01_prompts.json", "w"), ensure_ascii=False, indent=1)
open(ROOT / "prompts/EP01_prompts.md", "w").write("\n".join(md))

for s in segs:
    print(f"{s['shot']:6s} {s['start']:6.2f}-{s['end']:6.2f} ({s['duration']:4.2f}) {s['kind']:4s} | {s['phrase'][:70]}")
print("cut", cut, "duration", tl["duration"], "frames", tl["total_frames"])

# ---- human-readable scene map (docs/EP01_SCENE_MAP.md)
sm = ["# EP01 «СТАКАН ВОДЫ» — scene map\n",
      "Generated from `timeline/EP01_timeline.json` (output time, 24 fps). Times include the atmospheric pauses: "
      + ", ".join(f"+{p['seconds']}s at {p['output_t']:.2f}" for p in tl["atmospheric_pauses"]) + f". Hard cut to black at {cut:.2f}s, end card to {tl['duration']:.2f}s.\n",
      "| # | Shot | In–Out (s) | Dur | Type | VO | Picture | SFX |", "|---|---|---|---|---|---|---|---|"]
for s in segs:
    sm.append(f"| {s['scene']} | {s['shot']} | {s['start']:.2f}–{s['end']:.2f} | {s['duration']:.2f} | {s['kind']} | {s['phrase']} | {s['visual']} | "
              + ", ".join(x['effect'] for x in s['sfx']) + " |")
(ROOT / "docs").mkdir(exist_ok=True)
open(ROOT / "docs/EP01_SCENE_MAP.md", "w").write("\n".join(sm) + "\n")
