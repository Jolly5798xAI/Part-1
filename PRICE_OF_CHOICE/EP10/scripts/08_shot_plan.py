"""Write docs/EP10_SHOT_PLAN.md from the timeline (timeline_ep10.py) and the shot descriptions in scripts/render3d/shots.js."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import timeline_ep10 as TL

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
js = open(os.path.join(ROOT, "scripts", "render3d", "shots.js"), encoding="utf8").read()
DESC = {m.group(1): m.group(2).replace("\\'", "'") for m in re.finditer(r"^\s+(\w+): \{ desc: '((?:[^'\\]|\\.)*)'", js, re.M)}
src_job = {}
for m in re.finditer(r'(?:still|anim)\("(\w+)", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1)] = m.group(2)
for m in re.finditer(r'still\(f"(\w+)_\{m\}", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1) + "_neutral"] = m.group(2)
REUSED = {"E9_cop_screen_close": "EP09's last frame (the officer's phone, red «Оригинал должен умереть»), reused unchanged — EP10 starts the same second",
          "E8_feedc": "EP08 lip-sync stills of the sister's close feed, reused unchanged (her voice from every phone)",
          "S05_place_glass": "EP01 still: Alex putting the glass of water by the door — flashback, reused unchanged",
          "S06_phone_bank": "EP01 still: the bank app on his phone (+500 $ drawn in code) — flashback, reused unchanged"}


def vo_for(a, b):
    return " ".join(re.sub(r"[*!]", "", t).replace("¡", "!") for s, e, t in TL.SUBS if s < b and e > a) or "—"   # EP10: ¡ is a literal «!»


rows = []
for i, s in enumerate(TL.SHOTS, 1):
    a, b = s["t"]; src = s["src"]
    if src == "BLACK": frame, desc = "black", "hard cut — nothing after «…из-за двери комнаты двести четыре»"
    elif src == "LIPSYNC": frame = f"LIPSYNC `{s['lips']}_*`"; desc = REUSED.get(s["lips"]) or DESC.get(src_job.get(s["lips"] + "_neutral", ""), "")
    else: frame = f"`{src}`"; desc = REUSED.get(src) or DESC.get(src_job.get(src, src), "") or DESC.get(src, "")
    extra = [f"{k}: {s[k]}" for k in ("monitor", "monitors", "phone", "screens") if s.get(k)] + ([f"fx: {', '.join(s['fx'])}"] if s.get("fx") else []) + (["animated"] if "anim" in s else [])
    rows.append(f"| {i} | {a:.2f}–{b:.2f} | {frame} | {vo_for(a, b)} | {desc}{' · ' + '; '.join(extra) if extra else ''} |")
md = ["# EP10 «СОЗДАТЕЛЬ» — shot plan", "",
      f"Built from the final voiceover ({TL.VO_END:.2f} s, VO clock). Source of truth: `scripts/timeline_ep10.py`; this table is generated by",
      f"`scripts/08_shot_plan.py`. Hard cut to black at {TL.CUT_TO_BLACK:.2f} s on the last word «…четыре»; the file ends with the MP3 at {TL.END:.2f} s.",
      "No shot is longer than 4.5 s. Production names (ALEX_48 / ALEX_49 / ALEX_ZERO / ALEX_OLD_POLICE / SISTER) never appear on screen.", "",
      "| # | time | frame | VO | picture / notes |", "|---|---|---|---|---|"] + rows + ["",
      "Not shown, on purpose: what happens to the sister after the scream, who runs the game now, anything of EP11. No blood, no violence:",
      "ALEX_ZERO's disappearance is the series' block dissolve (EP07's cyan edge).", "",
      "## On-screen texts (exact, drawn in code with the series fonts, none before the VO says it)",
      f"The officer's phone (EP09's final screen, carried over): «{TL.MSG_DIE}».",
      f"The choice: «{TL.MSG_KILL}» ({TL.CHOICE10['t1']:.2f}), «{TL.MSG_STOP}» ({TL.CHOICE10['t2']:.2f}); tap {TL.T_TAP:.2f}; red {TL.T_RED:.2f}; «{TL.MSG_DENY}» ({TL.T_DENY:.2f}).",
      f"The sister's monitor in room 204: «{TL.MSG_PROJ}» ({TL.T_PROJ:.2f}), «Создатель:» ({TL.T_CREATOR:.2f}) «Елена» ({TL.T_NAME:.2f}). The recording's caption «КОМНАТА 204» ({TL.T_CAP:.2f}).",
      f"The dead phone: «{TL.MSG_LVL}» ({TL.T_LVL:.2f}), «Следующий игрок:» ({TL.T_NEXT:.2f}) «Елена» ({TL.T_NEXT_NAME:.2f}).",
      "Wrist numbers (3D pixel digits, no font): «48» on ALEX_48's forearm, «49» cyan on ALEX_49, «0» red on ALEX_ZERO.", ""]
open(os.path.join(ROOT, "docs", "EP10_SHOT_PLAN.md"), "w", encoding="utf8").write("\n".join(md))
print("wrote docs/EP10_SHOT_PLAN.md", len(rows), "shots")
