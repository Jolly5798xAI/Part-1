"""Write docs/EP09_SHOT_PLAN.md from the timeline (timeline_ep09.py) and the shot descriptions in scripts/render3d/shots.js."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import timeline_ep09 as TL

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
js = open(os.path.join(ROOT, "scripts", "render3d", "shots.js"), encoding="utf8").read()
DESC = {m.group(1): m.group(2).replace("\\'", "'") for m in re.finditer(r"^\s+(\w+): \{ desc: '((?:[^'\\]|\\.)*)'", js, re.M)}
src_job = {}
for m in re.finditer(r'(?:still|anim)\("(\w+)", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1)] = m.group(2)
for m in re.finditer(r'still\(f"(\w+)_\{m\}", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1) + "_neutral"] = m.group(2)
REUSED = {"E8_rec_knife": "EP08 still: the recording of tomorrow, the knife in the fist — reused unchanged (the visual link to EP08)", "E8_feedc": "EP08 lip-sync stills of the sister's close feed, reused unchanged (here seen through the cracked phone)", "E9_lock": "EP08's lock close-up (shot E8_lock) re-rendered — the thumb-turn fully turned, EP08's last frame"}


def vo_for(a, b):
    return " ".join(re.sub(r"[*!]", "", t).replace("¡", "!") for s, e, t in TL.SUBS if s < b and e > a) or "—"   # EP09: ¡ is a literal «!»


rows = []
for i, s in enumerate(TL.SHOTS, 1):
    a, b = s["t"]; src = s["src"]
    if src == "BLACK": frame, desc = "black", "hard cut — nothing after «Оригинал должен умереть»"
    elif src == "LIPSYNC": frame = f"LIPSYNC `{s['lips']}_*`"; desc = REUSED.get(s["lips"]) or DESC.get(src_job.get(s["lips"] + "_neutral", ""), "")
    else: frame = f"`{src}`"; desc = REUSED.get(src) or DESC.get(src_job.get(src, src), "") or DESC.get(src, "")
    extra = [f"{k}: {s[k]}" for k in ("monitor", "monitors", "phone") if s.get(k)] + ([f"fx: {', '.join(s['fx'])}"] if s.get("fx") else []) + (["animated"] if "anim" in s else [])
    rows.append(f"| {i} | {a:.2f}–{b:.2f} | {frame} | {vo_for(a, b)} | {desc}{' · ' + '; '.join(extra) if extra else ''} |")
md = ["# EP09 «ПЕРВЫЙ АЛЕКС» — shot plan", "",
      f"Built from the final voiceover ({TL.VO_END:.2f} s, VO clock). Source of truth: `scripts/timeline_ep09.py`; this table is generated by",
      f"`scripts/08_shot_plan.py`. Hard cut to black at {TL.CUT_TO_BLACK:.2f} s on the last word «умереть»; the file ends with the MP3 at {TL.END:.2f} s.",
      "No shot is longer than 4.5 s. Production names (ALEX_48 / ALEX_49 / ALEX_ZERO / ALEX_OLD_POLICE) never appear on screen.", "",
      "| # | time | frame | VO | picture / notes |", "|---|---|---|---|---|"] + rows + ["",
      "Not shown, on purpose: the original's death, who really runs the game, what the «0» finally means, anything after the last line.",
      "No blood, no stabbing of a person: the only strike hits the phone.", "",
      "## On-screen texts (exact, drawn in code with the series fonts, none before the VO says it)",
      f"ALEX_49's phone (lock screen {TL.PHONE_CLOCK}, «суббота, 7 ноября»): «{TL.MSG_TASK1}» ({TL.T_TASK1:.2f}), «{TL.MSG_TASK2}» ({TL.T_TASK2:.2f}); cracked from {TL.T_CRACK:.2f}.",
      f"The officer's phone: «{TL.MSG_FOUND}» ({TL.T_MSG1:.2f}), «{TL.MSG_CHECK}» ({TL.T_MSG2:.2f}), then full-screen red «{TL.MSG_DIE}» ({TL.T_MSG3:.2f}).",
      f"Wrist numbers (3D pixel digits, no font): «48» ink on ALEX_48's forearm (EP07), «49» cyan on ALEX_49 (lit by {TL.T_49:.2f}), «0» red on ALEX_ZERO ({TL.T_ZERO_ON:.2f} → {TL.T_ZERO:.2f}).", ""]
open(os.path.join(ROOT, "docs", "EP09_SHOT_PLAN.md"), "w", encoding="utf8").write("\n".join(md))
print("wrote docs/EP09_SHOT_PLAN.md", len(rows), "shots")
