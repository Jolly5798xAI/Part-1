"""Write docs/EP08_SHOT_PLAN.md from the timeline (timeline_ep08.py) and the shot descriptions in scripts/render3d/shots.js."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import timeline_ep08 as TL

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
js = open(os.path.join(ROOT, "scripts", "render3d", "shots.js"), encoding="utf8").read()
DESC = {m.group(1): m.group(2).replace("\\'", "'") for m in re.finditer(r"^\s+(\w+): \{ desc: '((?:[^'\\]|\\.)*)'", js, re.M)}
src_job = {}
for m in re.finditer(r'(?:still|anim)\("(\w+)", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1)] = m.group(2)
for m in re.finditer(r'still\(f"(\w+)_\{m\}", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1) + "_neutral"] = m.group(2)
REUSED = {"E7_mon": "EP07 still (its last shot), reused unchanged", "E7_feedm": "EP07 lip-sync stills of the sister's feed, reused unchanged"}


def vo_for(a, b):
    return " ".join(re.sub(r"[*!¡]", "", t) for s, e, t in TL.SUBS if s < b and e > a) or "—"


rows = []
for i, s in enumerate(TL.SHOTS, 1):
    a, b = s["t"]; src = s["src"]
    if src == "BLACK": frame, desc = "black", "hard cut — nothing after EP01's line"
    elif src == "LIPSYNC": frame = f"LIPSYNC `{s['lips']}_*`"; desc = REUSED.get(s["lips"]) or DESC.get(src_job.get(s["lips"] + "_neutral", ""), "")
    else: frame = f"`{src}`"; desc = REUSED.get(src) or DESC.get(src_job.get(src, src), "")
    extra = [f"{k}: {s[k]}" for k in ("monitor", "monitors", "phone") if s.get(k)] + ([f"fx: {', '.join(s['fx'])}"] if s.get("fx") else []) + (["animated"] if "anim" in s else [])
    rows.append(f"| {i} | {a:.2f}–{b:.2f} | {frame} | {vo_for(a, b)} | {desc}{' · ' + '; '.join(extra) if extra else ''} |")
md = ["# EP08 «ЗАВТРАШНИЙ ДЕНЬ» — shot plan", "",
      f"Built from the final voiceover ({TL.VO_END:.2f} s, VO clock). Source of truth: `scripts/timeline_ep08.py`; this table is generated by",
      f"`scripts/08_shot_plan.py`. Hard cut to black at {TL.CUT_TO_BLACK:.2f} s on the last word «воды»; the file ends with the MP3 at {TL.END:.2f} s.",
      "No shot is longer than 4.5 s. Production names (ALEX_48 / ALEX_ORIGINAL / ALEX_FIRST) never appear on screen.", "",
      "| # | time | frame | VO | picture / notes |", "|---|---|---|---|---|"] + rows + ["",
      "Not shown, on purpose: who is behind the door (ALEX_FIRST is only a voice), how many copies exist, how the loop works, the knife",
      "being used (the recording stops on the plea), anything after the last line.", "",
      "## On-screen texts (exact, drawn in code with the series fonts, none before the VO says it)",
      f"Centre monitor (EP07's screen, already complete): «{TL.ADDR_STREET}», «{TL.ADDR_FLAT}», «{TL.DATE_TEXT}», stamp «{TL.DATE_WORD}».",
      f"Recording: «REC», «{TL.REC_STAMP}  02:54:ss» (from {TL.T_REC:.2f}). Wall monitors: «УДАЛЕНИЕ» + «00:10» (from {TL.T_MON_RED:.2f}).",
      f"Centre monitor: «{' '.join(TL.MSG_DELETE10)}» typed from {TL.T_DEL:.2f} + the timer; HUD timer 00:10 → 00:00 ({TL.COUNTDOWN[1]:.2f} → {TL.T_ZERO:.2f}).",
      f"Phone (lock screen, {TL.PHONE_CLOCK}): «{TL.DATE_OLD}» breaks up and flips to «{TL.DATE_TEXT}» ({TL.T_FLIP:.2f}); cards «{TL.MSG_CHANGED}» ({TL.T_CHANGED:.2f}),",
      f"«{TL.MSG_TOMORROW}» ({TL.T_TOMORROW8:.2f}). Door of flat 47 (landing side): brass plate «47» in the 3D pixel digits (no font).", "",
      "**The date.** EP01's lock screen: «пятница, 6 ноября»; EP07's monitor: «суббота, 7 ноября» + «ЗАВТРА». EP08 keeps exactly that. No real-world date.", ""]
open(os.path.join(ROOT, "docs", "EP08_SHOT_PLAN.md"), "w", encoding="utf8").write("\n".join(md))
print("wrote docs/EP08_SHOT_PLAN.md", len(rows), "shots")
