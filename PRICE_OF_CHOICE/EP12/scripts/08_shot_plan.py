"""Write docs/EP12_SHOT_PLAN.md from the timeline (timeline_ep12.py) and the shot descriptions in scripts/render3d/shots.js."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import timeline_ep12 as TL

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
js = open(os.path.join(ROOT, "scripts", "render3d", "shots.js"), encoding="utf8").read()
DESC = {m.group(1): m.group(2).replace("\\'", "'") for m in re.finditer(r"^\s+(\w+): \{ desc: '((?:[^'\\]|\\.)*)'", js, re.M)}
src_job = {}
for m in re.finditer(r'(?:still|anim)\("(\w+)", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1)] = m.group(2)
for m in re.finditer(r'still\(f"(\w+)_\{m\}", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1) + "_neutral"] = m.group(2)
REUSED = {"E11_face_close": "EP11's last frame (the computer turned to ALEX_48, the screen filling the frame), reused unchanged — the screen content is drawn by phone_ui", "E11_face": "EP11's turned computer with the chained sister behind it, reused unchanged", "E11_sisr": "EP11's red close-up of the chained sister (lip-sync set), reused unchanged"}

def vo_for(a, b):
    return " ".join(re.sub(r"[*!]", "", t).replace("¡", "!") for s, e, t in TL.SUBS if s < b and e > a) or "—"   # EP10: ¡ is a literal «!»


rows = []
for i, s in enumerate(TL.SHOTS, 1):
    a, b = s["t"]; src = s["src"]
    if src == "BLACK": frame, desc = "black", "—"
    elif src == "LIPSYNC": frame = f"LIPSYNC `{s['lips']}_*`"; desc = REUSED.get(s["lips"]) or DESC.get(src_job.get(s["lips"] + "_neutral", ""), "")
    else: frame = f"`{src}`"; desc = REUSED.get(src) or DESC.get(src_job.get(src, src), "") or DESC.get(src, "")
    extra = [f"{k}: {s[k]}" for k in ("monitor", "monitors", "phone", "screens") if s.get(k)] + ([f"fx: {', '.join(s['fx'])}"] if s.get("fx") else []) + (["animated"] if "anim" in s else [])
    rows.append(f"| {i} | {a:.2f}–{b:.2f} | {frame} | {vo_for(a, b)} | {desc}{' · ' + '; '.join(extra) if extra else ''} |")
md = ["# EP12 «ПЕРВОЕ ИСПЫТАНИЕ» — shot plan", "",
      f"Built from the final voiceover ({TL.VO_END:.2f} s, VO clock). Source of truth: `scripts/timeline_ep12.py`; this table is generated by",
      f"`scripts/08_shot_plan.py`. The speech runs to the end of the MP3, so the episode stops dead on «Не верь мне» at {TL.END:.2f} s (no black tail).",
      "No shot is longer than 4.5 s. Production names (ALEX_48 / ALEX_ORIGINAL_CONSCIOUSNESS / ELENA_204 / ELENA_APARTMENT) never appear on screen.", "",
      "| # | time | frame | VO | picture / notes |", "|---|---|---|---|---|"] + rows + ["",
      "Not shown, on purpose: who sent the first task, which Elena is real, where the second one came from, why the system chose 48, what the",
      "original will do about the handover. The accident is a recording: the person on the road, the foot on the brake, the car sliding on with",
      "its brake lights burning — and the record dies before anything happens (no collision, no injuries).", "",
      "## On-screen texts (exact, drawn in code with the series fonts, none before the VO says it)",
      f"Dashboard phone (night, three years ago): «{TL.MSG_TASK1}» ({TL.T_TASK1:.2f}), «{TL.MSG_TASK2}» ({TL.T_TASK2:.2f}), «{TL.MSG_TASK3}» ({TL.T_TASK3:.2f}).",
      f"The sister's monitor on the second recording: «> {TL.MSG_CMD}» typed from {TL.T_CMD:.2f}.",
      f"The turned screen: 47 red copies ({TL.T_GRID:.2f}), one lit cyan ({TL.T_GRID_CYAN:.2f}); «{TL.MSG_HAND}» ({TL.T_HAND:.2f}), «{TL.MSG_NEWADM}» ({TL.T_NEWADM:.2f}) + «48» ({TL.T_48:.2f}).",
      f"The side monitor: lit {TL.T_SIDE_ON:.2f}, «{TL.MSG_LIVE}» ({TL.T_LIVE:.2f}), «{TL.MSG_FLAT}» ({TL.T_FLAT:.2f}), «{TL.MSG_TWO}» ({TL.T_TWO:.2f}).", ""]
open(os.path.join(ROOT, "docs", "EP12_SHOT_PLAN.md"), "w", encoding="utf8").write("\n".join(md))
print("wrote docs/EP12_SHOT_PLAN.md", len(rows), "shots")
