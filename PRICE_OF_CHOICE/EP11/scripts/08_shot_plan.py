"""Write docs/EP11_SHOT_PLAN.md from the timeline (timeline_ep11.py) and the shot descriptions in scripts/render3d/shots.js."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import timeline_ep11 as TL

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
js = open(os.path.join(ROOT, "scripts", "render3d", "shots.js"), encoding="utf8").read()
DESC = {m.group(1): m.group(2).replace("\\'", "'") for m in re.finditer(r"^\s+(\w+): \{ desc: '((?:[^'\\]|\\.)*)'", js, re.M)}
src_job = {}
for m in re.finditer(r'(?:still|anim)\("(\w+)", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1)] = m.group(2)
for m in re.finditer(r'still\(f"(\w+)_\{m\}", "(\w+)"', open(os.path.join(ROOT, "scripts", "02_render_illustrations.py")).read()):
    src_job[m.group(1) + "_neutral"] = m.group(2)
REUSED = {"E10_pov_end": "EP10's last phone frame (ALEX_48's POV, the dead screen with «Уровень десять завершён» / «Следующий игрок: Елена»), reused unchanged — EP11 starts the same second"}

def vo_for(a, b):
    return " ".join(re.sub(r"[*!]", "", t).replace("¡", "!") for s, e, t in TL.SUBS if s < b and e > a) or "—"   # EP10: ¡ is a literal «!»


rows = []
for i, s in enumerate(TL.SHOTS, 1):
    a, b = s["t"]; src = s["src"]
    if src == "BLACK": frame, desc = "black", "—"
    elif src == "LIPSYNC": frame = f"LIPSYNC `{s['lips']}_*`"; desc = REUSED.get(s["lips"]) or DESC.get(src_job.get(s["lips"] + "_neutral", ""), "")
    else: frame = f"`{src}`"; desc = REUSED.get(src) or DESC.get(src_job.get(src, src), "") or DESC.get(src, "")
    extra = [f"{k}: {s[k]}" for k in ("monitor", "monitors", "phone", "screens") if s.get(k)] + ([f"fx: {', '.join(s['fx'])}"] if s.get("fx") else []) + (["animated"] if "anim" in s else [])
    rows.append(f"| {i} | {a:.2f}–{b:.2f} | {frame} | {vo_for(a, b)} | {desc}{' · ' + '; '.join(extra) if extra else ''} |")
md = ["# EP11 «НУЛЕВОЙ УРОВЕНЬ» — shot plan", "",
      f"Built from the final voiceover ({TL.VO_END:.2f} s, VO clock). Source of truth: `scripts/timeline_ep11.py`; this table is generated by",
      f"`scripts/08_shot_plan.py`. The speech runs to the end of the MP3, so the episode stops dead on «Оригинал проснулся» at {TL.END:.2f} s (no black tail).",
      "No shot is longer than 4.5 s. Production names (ALEX_48 / ALEX_49 / ALEX_OLD_POLICE / SISTER / ALEX_ORIGINAL_CONSCIOUSNESS) never appear on screen.", "",
      "| # | time | frame | VO | picture / notes |", "|---|---|---|---|---|"] + rows + ["",
      "Not shown, on purpose: what the original does next, why he wants the copies destroyed, who really runs the system. ALEX_ZERO is not on",
      "screen and is never identified with the face on the monitor. No blood, no injuries: the hospital shows a bandage, a drip and a heart monitor;",
      "the officer and ALEX_49 vanish with the series' block dissolve (EP07's cyan edge).", "",
      "## On-screen texts (exact, drawn in code with the series fonts, none before the VO says it)",
      f"ALEX_48's phone (EP10's last screen, carried over): «Следующий игрок:» ({TL.T_NEXT:.2f}) «Елена» ({TL.T_NEXT_NAME:.2f}).",
      f"The screen in front of the sister: «{TL.MSG_TITLE}» ({TL.T_TITLE:.2f}), «{TL.MSG_OPT1}» ({TL.T_OPT1:.2f}) «{TL.MSG_OR} {TL.MSG_OPT2}» ({TL.T_OPT2:.2f}).",
      f"Red ({TL.T_RED:.2f}): «{TL.MSG_ZERO}» ({TL.T_ZERO:.2f}), «{TL.MSG_DEL}» ({TL.T_DEL:.2f}).",
      f"The side monitor: the hospital recording from {TL.T_REC:.2f} (REC, date {TL.HOSP_STAMP}: three years before EP10's «ПТ 06.11»); copies of his face from {TL.T_COPIES:.2f}.",
      f"The turned screen: his face, eyes closed ({TL.T_FACE:.2f}), eyes open ({TL.T_EYES:.2f}), «{TL.MSG_LINK}» ({TL.T_MSG1:.2f}), «{TL.MSG_WOKE}» ({TL.T_MSG2:.2f}) — the last frame.",
      "Wrist numbers (3D pixel digits, no font): «48» on ALEX_48's forearm, «49» cyan on ALEX_49.", ""]
open(os.path.join(ROOT, "docs", "EP11_SHOT_PLAN.md"), "w", encoding="utf8").write("\n".join(md))
print("wrote docs/EP11_SHOT_PLAN.md", len(rows), "shots")
